#!/usr/bin/env python3
"""
Tân Hưng Hà - Offline Licensing Model (OLM)
Module: Sinh Cặp Khóa Ed25519 & Xuất Khóa C++ Header cho PDA

Chức năng:
1. Sinh Private Key Ed25519 (Lưu trữ tuyệt mật tại THH, không bao giờ nhúng vào app).
2. Sinh Public Key Ed25519 (Dạng PEM và Raw 32 bytes).
3. Xuất file C++ header (public_key.h) với cơ chế XOR Masking để nhúng vào Android NDK C++.
"""

import os
import sys
import argparse
from cryptography.hazmat.primitives.asymmetric import ed25519
from cryptography.hazmat.primitives import serialization

if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding='utf-8')
        sys.stderr.reconfigure(encoding='utf-8')
    except Exception:
        pass

XOR_MASK = 0x5A  # Mặt nạ xáo trộn để giấu Public Key trong file .so

def generate_ed25519_keys(out_dir: str = "."):
    os.makedirs(out_dir, exist_ok=True)
    
    pri_pem_path = os.path.join(out_dir, "ed25519_private_key.pem")
    pub_pem_path = os.path.join(out_dir, "ed25519_public_key.pem")
    pub_raw_path = os.path.join(out_dir, "ed25519_public_key.bin")
    cpp_header_path = os.path.join(out_dir, "public_key.h")

    # 1. Sinh Private Key Ed25519
    private_key = ed25519.Ed25519PrivateKey.generate()
    
    pri_bytes = private_key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption()
    )
    with open(pri_pem_path, "wb") as f:
        f.write(pri_bytes)

    # 2. Sinh Public Key
    public_key = private_key.public_key()
    pub_bytes = public_key.public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo
    )
    with open(pub_pem_path, "wb") as f:
        f.write(pub_bytes)

    # Raw 32-byte Public Key
    raw_pub = public_key.public_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PublicFormat.Raw
    )
    with open(pub_raw_path, "wb") as f:
        f.write(raw_pub)

    # 3. Tạo file C++ Header với XOR Obfuscation
    masked_bytes = [b ^ XOR_MASK for b in raw_pub]
    hex_str = ", ".join([f"0x{b:02X}" for b in masked_bytes])

    cpp_content = f"""// Auto-generated by keygen.py - DO NOT EDIT MANUALLY
#ifndef OLM_PUBLIC_KEY_H
#define OLM_PUBLIC_KEY_H

#include <stdint.h>
#include <string.h>

// Ed25519 32-byte Public Key (Masked with XOR 0x{XOR_MASK:02X} to prevent hex dumping)
static const uint8_t OLM_MASKED_PUBKEY[32] = {{
    {hex_str}
}};

static const uint8_t OLM_PUBKEY_XOR_MASK = 0x{XOR_MASK:02X};

// Hàm khôi phục Public Key trong bộ nhớ RAM tạm thời
static inline void olm_get_public_key(uint8_t out_key[32]) {{
    for (int i = 0; i < 32; ++i) {{
        out_key[i] = OLM_MASKED_PUBKEY[i] ^ OLM_PUBKEY_XOR_MASK;
    }}
}}

// Xóa sạch vùng nhớ sau khi dùng xong (Zeroize RAM)
static inline void olm_clean_key_memory(uint8_t key[32]) {{
    volatile uint8_t* p = key;
    for (int i = 0; i < 32; ++i) {{
        p[i] = 0;
    }}
}}

#endif // OLM_PUBLIC_KEY_H
"""
    with open(cpp_header_path, "w", encoding="utf-8") as f:
        f.write(cpp_content)

    print("=" * 60)
    print(" SINH CẶP KHÓA ED25519 THÀNH CÔNG")
    print("=" * 60)
    print(f"[!] Private Key (Bảo mật tại THH) : {pri_pem_path}")
    print(f"[+] Public Key PEM                : {pub_pem_path}")
    print(f"[+] Public Key Raw (32-byte)      : {pub_raw_path}")
    print(f"[+] C++ Header cho Android NDK    : {cpp_header_path}")
    print(f"[+] Raw Hex: {raw_pub.hex().upper()}")
    print("=" * 60)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Sinh cặp khóa Ed25519 cho OLM")
    parser.add_argument("--out", default=".", help="Thư mục xuất file khóa (mặc định: thư mục hiện tại)")
    args = parser.parse_args()
    generate_ed25519_keys(args.out)
